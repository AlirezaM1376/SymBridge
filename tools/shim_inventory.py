#!/usr/bin/env python3
"""Inventory ordinal registrations found by import_coverage.py's source scanner.

Usage:
    python tools/shim_inventory.py
    python tools/shim_inventory.py --src src --out tools/shim_inventory.md
"""

import argparse
import collections
import os

from import_coverage import (
    function_bodies,
    load_importmap_h,
    read,
    scan_body,
    second_param_name,
    shim_table_entries,
    source_files,
    strip_comments,
)

HERE = os.path.dirname(os.path.abspath(__file__))


# Earlier dispatchers win when they return a non-zero shim address.
DISPATCH_ORDER = {
    "GfxShimFor": 1,
    "GfxShimFor (gfxfake table)": 1,
    "CtlRegShimFor": 2,
    "CtlRegShimFor (ctlreg table)": 2,
    "FsShimFor (fsshim table)": 3,
    "FsShimFor": 3,
    "ThreadShimFor": 4,
    "ThreadShimFor (threadshim table)": 4,
    "SchedShimFor (schedshim table)": 8,
    "RtShimFor (rtshim table)": 6,
    "RtShimFor": 6,
    "AudioShimFor (audioshim table)": 7,
    "AudioShimFor": 7,
    "SchedShimFor": 8,
    "HostShimFor": 9,
    "ShimFor": 10,
}


def collect(src):
    import_map = load_importmap_h(src)
    registrations = []
    unparsed = []
    pattern = r"\b(\w*ShimFor)\s*\((?P<params>[^()]*)\)"

    for filename in source_files(src):
        text = strip_comments(read(os.path.join(src, filename)))
        for match, body in function_bodies(text, pattern):
            ordinal_var = second_param_name(match.group("params"))
            if not ordinal_var:
                continue
            found = set()
            missed = []
            function = match.group(1)
            scan_body(body, ordinal_var, found, missed, "%s:%s" % (filename, function))
            unparsed.extend(missed)
            for dll, ordinal in sorted(found):
                entry = import_map.get((dll, ordinal), {})
                registrations.append({
                    "dll": dll,
                    "ordinal": ordinal,
                    "function": entry.get("name", "(not in merged map)"),
                    "registration": function,
                    "file": filename,
                })
        for _table_name, dll, ordinal, _address, owner in shim_table_entries(text):
            entry = import_map.get((dll, ordinal), {})
            wrappers = {
                "ctlreg": "CtlRegShimFor",
                "fsshim": "FsShimFor",
                "gfxfake": "GfxShimFor",
                "rtshim": "RtShimFor",
                "audioshim": "AudioShimFor",
                "schedshim": "SchedShimFor",
                "threadshim": "ThreadShimFor",
            }
            wrapper = wrappers.get(owner, owner)
            registrations.append({
                "dll": dll,
                "ordinal": ordinal,
                "function": entry.get("name", "(not in merged map)"),
                "registration": "%s (%s table)" % (wrapper, owner),
                "file": filename,
            })

    return sorted(registrations, key=lambda row: (
        row["dll"], row["ordinal"], row["file"], row["registration"]
    )), unparsed


def duplicate_winner(owners):
    ranked = sorted(
        owners,
        key=lambda row: DISPATCH_ORDER.get(row["registration"], 99),
    )
    best_rank = DISPATCH_ORDER.get(ranked[0]["registration"], 99)
    tied = [row for row in ranked if DISPATCH_ORDER.get(row["registration"], 99) == best_rank]
    if len(tied) == 1:
        winner = tied[0]
        return "%s in %s (earliest dispatch path)" % (winner["registration"], winner["file"])
    return "tied at function granularity; inspect the specific branch order in the listed files"


def build_report(src):
    registrations, unparsed = collect(src)
    pairs = collections.defaultdict(list)
    for row in registrations:
        pairs[(row["dll"], row["ordinal"])].append(row)
    duplicates = {key: owners for key, owners in pairs.items() if len(owners) > 1}
    unique_pairs = len(pairs)

    lines = [
        "# Shim Registration Inventory",
        "",
        "Generated by `tools/shim_inventory.py`, using `import_coverage.py`'s source scanner and the current `src/importmap_data.cpp` function names.",
        "Each row is one scanner-recognized static registration `(DLL, old ordinal, function, registration function/file)`. ",
        "",
        "- Registrations: %d" % len(registrations),
        "- Unique `(DLL, ordinal)` pairs: %d" % unique_pairs,
    ]
    lines.append("- **no duplicates**" if not duplicates else "- Duplicate pairs: %d" % len(duplicates))
    lines.extend([
        "- Unparsed lines: %d; see Scanner Warnings below." % len(unparsed),
        "",
        "## Registrations",
        "",
        "| DLL | Old ordinal | Imported function | Registration function | File |",
        "|---|---:|---|---|---|",
    ])
    for row in registrations:
        lines.append("| %s | %d | %s | %s | %s |" % (
            row["dll"], row["ordinal"], row["function"], row["registration"], row["file"]
        ))

    lines.extend(["", "## Duplicate Review", ""])
    if not duplicates:
        lines.extend([
            "**no duplicates.** The scan found %d unique pairs across %d source files, with no `(DLL, ordinal)` registered more than once. There are no duplicate-specific winner notes to record." % (
                unique_pairs, len({row["file"] for row in registrations})
            ),
        ])
    else:
        lines.append("Duplicate registrations and current dispatch winners:")
        lines.append("")
        for (dll, ordinal), owners in sorted(duplicates.items()):
            lines.append("- `%s #%d`: %s. Winner: **%s**." % (
                dll,
                ordinal,
                "; ".join("%s in %s" % (row["registration"], row["file"]) for row in owners),
                duplicate_winner(owners),
            ))

    lines.extend([
        "",
        "Current dispatch precedence (earliest non-zero handler wins): `ShimFor` delegates to `HostShimFor` before its local fallback cases; `HostShimFor` checks `GfxShimFor`, `CtlRegShimFor`, `FsShimFor`, `ThreadShimFor`, old trap/untrap handlers, `RtShimFor`, `AudioShimFor`, and `SchedShimFor`, then its direct cases. `ShimFor` local cases are last. A reported tie means the scanner identified the containing functions but not the exact branch order within one function; inspect those branches before resolving it.",
        "",
        "## Scanner Warnings",
        "",
    ])
    if not unparsed:
        lines.append("No unparsed registration lines.")
    else:
        lines.append("The following lines mention the ordinal argument but are not direct ordinal registrations:")
        lines.append("")
        for where, code, reason in unparsed:
            lines.append("- `%s`: `%s` (%s)" % (where, code.replace("`", "'"), reason))
        lines.extend([
            "",
            "These are forwarding calls. The callees' direct ordinal cases are inventoried above; the forwarding lines themselves do not specify a DLL or ordinal.",
        ])
    lines.append("")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--src", default=os.path.join(HERE, "..", "src"), help="host source directory (default: ../src)")
    parser.add_argument("--out", default=os.path.join(HERE, "shim_inventory.md"), help="Markdown output path (default: shim_inventory.md)")
    args = parser.parse_args()

    if not os.path.isdir(args.src):
        parser.error("source directory does not exist: %s" % args.src)
    report = build_report(args.src)
    with open(args.out, "w", encoding="utf-8", newline="\n") as output:
        output.write(report)
    registrations, unparsed = collect(args.src)
    pairs = {(row["dll"], row["ordinal"]) for row in registrations}
    duplicate_count = len(registrations) - len(pairs)
    print("wrote %d registrations (%d unique pairs, %d duplicate entries, %d unparsed lines) to %s" % (
        len(registrations), len(pairs), duplicate_count, len(unparsed), args.out
    ))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
