#!/usr/bin/env python3
"""Coverage report for ALL games: writes docs/COVERAGE.md.

  python coverage_all.py            write <root>/docs/COVERAGE.md
  python coverage_all.py --check    do not write; exit 1 if the file on disk is not what would be generated
  python coverage_all.py --out F    write somewhere else

Reads  : <root>/games/<id>/game.json, the main map CSV and baseline.log of every game, <root>/src (shim registry,
         importmap_data.cpp). The classification (shim / direct / trap) is the one import_coverage.py uses.
Writes : docs/COVERAGE.md (no dates or machine names in it, so it only changes when the data changes).
Parts  : 1 one row per game   2 import matrix (which import is used by how many games)
         3 static prediction vs what the device runs reached
Only the main version of each game is used. Exit: 0 ok, 1 --check found a difference, 2 error.
"""
import argparse
import collections
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import gamelog          # noqa: E402
import import_coverage as IC   # noqa: E402


def load_games(root):
    """-> list of dicts, one per game folder, sorted by id. ValueError (naming the game) when a game cannot be read."""
    gdir = os.path.join(root, "games")
    if not os.path.isdir(gdir):
        raise ValueError("no games folder: %s" % gdir)
    games = []
    for gid in sorted(d for d in os.listdir(gdir) if os.path.isdir(os.path.join(gdir, d))):
        folder = os.path.join(gdir, gid)
        try:
            with open(os.path.join(folder, "game.json"), "r", encoding="utf-8") as f:
                m = json.load(f)
            main = next((v for v in m["versions"] if v["id"] == "main"), None)
            if main is None:
                raise ValueError("no main version")
            log = gamelog.read_lines(os.path.join(folder, main["baseline"])) if "baseline" in main else []
            summ = {}
            for ln in log:
                if ln.startswith("SUMMARY "):
                    summ = dict(re.findall(r"(\w+)=(\S+)", ln))
            games.append({"id": gid, "name": m["name"], "status": m.get("status", "not_tested"),
                          "rows": IC.load_csv(os.path.join(folder, main["map"])),
                          "summary": summ, "versions": len(m["versions"])})
        except (OSError, ValueError, KeyError, TypeError, AttributeError) as ex:
            raise ValueError("games/%s: %s" % (gid, ex if str(ex) else type(ex).__name__))
    return games


def classify_game(g, registry, base):
    cls, names = {}, {}
    for r in g["rows"]:
        key = (r["dll"].lower(), int(r["v2_ordinal"]))
        cls[key] = IC.classify(key[0], key[1], registry, base)
        if r.get("v2_name"):
            names[key] = r["v2_name"]
    g["cls"], g["names"] = cls, names
    g["count"] = collections.Counter(cls.values())


def build_matrix(games):
    """-> list of (state, games_using, dll, ordinal, name) for every import used by any game."""
    users = collections.defaultdict(list)
    state, name = {}, {}
    for g in games:
        for key, k in g["cls"].items():
            users[key].append(g["id"])
            state[key] = k
            if key in g["names"] and key not in name:
                name[key] = g["names"][key]
    order = {"trap": 0, "shim": 1, "direct": 2}
    rows = [(state[k], sorted(u), k[0], k[1], name.get(k, "-")) for k, u in users.items()]
    rows.sort(key=lambda r: (order[r[0]], -len(r[1]), r[2], r[3]))
    return rows


def render(games, matrix):
    L = []
    P = L.append
    P("# Import coverage of all games")
    P("")
    P("Generated by `tools/coverage_all.py` from `games/*/` and `src/`. Do not edit by hand; run `python tools/coverage_all.py`.")
    P("Only the main version of each game is counted. **shim** = a host implementation exists, **direct** = bound to the")
    P("real v3 function, **trap** = the game gets a stub that only matters if the game really calls it.")
    P("")
    P("## 1. Games")
    P("")
    P("| game | status | imports | direct | shim | trap | handled | reached | frames | run |")
    P("|---|---|---:|---:|---:|---:|---:|---:|---:|---|")
    tot = collections.Counter()
    for g in games:
        c, s = g["count"], g["summary"]
        n = sum(c.values())
        handled = 100.0 * (c["direct"] + c["shim"]) / n if n else 0.0
        tot.update(c)
        P("| %s | %s | %d | %d | %d | %d | %.0f%% | %s | %s | %s s, exit %s |" % (
            g["name"], g["status"], n, c["direct"], c["shim"], c["trap"], handled,
            s.get("reached", "?"), s.get("frames", "?"), s.get("secs", "?"), s.get("exit", "?")))
    P("")
    P("`handled` = (direct + shim) / imports. `reached` = unresolved imports (traps) the game really called during the run.")
    P("")
    P("## 2. Import matrix")
    P("")
    traps = [r for r in matrix if r[0] == "trap"]
    P("%d distinct imports are used by at least one game: %d trap, %d shim, %d direct. Traps used by the most games first." % (
        len(matrix), len(traps), sum(1 for r in matrix if r[0] == "shim"), sum(1 for r in matrix if r[0] == "direct")))
    P("")
    P("| state | games | dll | ordinal | name | used by |")
    P("|---|---:|---|---:|---|---|")
    for st, users, dll, o, nm in matrix:
        P("| %s | %d | %s | %d | %s | %s |" % (st, len(users), dll, o, IC.esc(nm)[:90], ", ".join(users)))
    P("")
    P("## 3. Static prediction vs device runs")
    P("")
    P("| game | traps (static) | reached on device | never reached | verdict |")
    P("|---|---:|---:|---:|---|")
    gaps = 0
    for g in games:
        t = g["count"]["trap"]
        try:
            r = int(g["summary"].get("reached", ""))
        except ValueError:
            P("| %s | %d | ? | ? | %s |" % (g["name"], t, "pending: no run accepted yet" if not g["summary"] else "no reached= in the SUMMARY"))
            continue
        gaps += 1 if r else 0
        P("| %s | %d | %d | %d | %s |" % (g["name"], t, r, max(t - r, 0),
                                          "gap: %d trap(s) called" % r if r else "harmless so far"))
    P("")
    if gaps:
        P("**Traps reached on a device: %d game(s) have a gap.** See the game's log for the `hits:` lines." % gaps)
    else:
        P("**Traps reached on a device: none, in all %d games.** The traps are stubs that no tested run has called." % len(games))
    P("")
    return "\n".join(L)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--root", default=os.path.dirname(HERE))
    ap.add_argument("--out", help="default: <root>/docs/COVERAGE.md")
    ap.add_argument("--check", action="store_true", help="exit 1 if the file on disk is out of date")
    a = ap.parse_args()
    out = a.out or os.path.join(a.root, "docs", "COVERAGE.md")
    try:
        registry, _ = IC.load_shim_registry(os.path.join(a.root, "src"))
        base = IC.load_importmap_h(os.path.join(a.root, "src"))
        games = load_games(a.root)
        for g in games:
            classify_game(g, registry, base)
    except (OSError, ValueError) as ex:
        print("coverage_all: cannot build the report: %s" % ex, file=sys.stderr)
        return 2
    text = render(games, build_matrix(games))
    if a.check:
        try:
            with open(out, "r", encoding="utf-8", newline="") as f:
                cur = f.read().replace("\r\n", "\n")
        except OSError:
            cur = None
        if cur != text:
            print("CHECK FAILED: %s is not up to date; run coverage_all.py" % out, file=sys.stderr)
            return 1
        print("check ok: %s is up to date" % os.path.basename(out))
        return 0
    try:
        os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)
        gamelog.write_text(out, text, "utf-8")         # temp file + rename: a failure never leaves a half-written report
    except OSError as ex:
        print("coverage_all: cannot write %s (%s)" % (out, ex.strerror or ex), file=sys.stderr)
        return 2
    print("wrote %s (%d games)" % (out, len(games)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
